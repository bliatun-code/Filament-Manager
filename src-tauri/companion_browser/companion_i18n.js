function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_match, token) => String(params[token] ?? ""));
}

function lookup(dictionary, key) {
  return String(key || "")
    .split(".")
    .filter(Boolean)
    .reduce((current, part) => {
      if (!current || typeof current === "string") {
        return undefined;
      }
      return current[part];
    }, dictionary);
}

export function normalizeCompanionLocale(locale) {
  const normalized = String(locale || "").trim().toLowerCase();
  return VALID_LOCALES.has(normalized) ? normalized : "en";
}

export function readStoredCompanionLocale(storageKey, storageRef) {
  return normalizeCompanionLocale(storageRef?.getItem?.(storageKey));
}

export function resolveInitialCompanionLocale(storageRef = localStorage, navigatorRef = navigator) {
  const storedValue = storageRef?.getItem?.(COMPANION_LOCALE_STORAGE_KEY);
  if (storedValue === "en" || storedValue === "nb") {
    return storedValue;
  }
  const language = String(navigatorRef?.language || "").trim().toLowerCase();
  if (language.startsWith("nb") || language.startsWith("no")) {
    return "nb";
  }
  return "en";
}

export function t(locale, key, fallback = "", params = {}) {
  const normalizedLocale = normalizeCompanionLocale(locale);
  const localized = lookup(dictionaries[normalizedLocale], key);
  if (typeof localized === "string") {
    return interpolate(localized, params);
  }
  if (fallback) {
    return interpolate(fallback, params);
  }
  return key;
}

export function formatCountLabel(locale, count, forms) {
  const normalizedLocale = normalizeCompanionLocale(locale);
  const resolvedForms = forms?.[normalizedLocale] ?? forms?.en ?? { one: "", other: "" };
  const noun = count === 1 ? resolvedForms.one : resolvedForms.other;
  return `${count} ${noun}`.trim();
}
